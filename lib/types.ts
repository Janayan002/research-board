// Shared data shapes for the whole app.

export type Source = { title: string; url: string };

// Where something came from — used to build citations (lib/citation.ts).
export type Citation = {
  title?: string; // title of the image/work, or the page it came from
  creator?: string; // artist, photographer or author
  siteName?: string; // website / publication
  pageUrl?: string; // the page the image was on
  imageUrl?: string; // the image file itself
  published?: string; // date the page/work was published (free text or ISO)
  accessed: string; // ISO date you saved it
};

export type Section = { label: string; text: string };

type BaseCard = {
  id: string;
  x: number; // position on the canvas (world units = frame pixels)
  y: number;
  w: number; // width; height grows with content
  scale?: number; // visual scale, so cards added while zoomed out are still readable
  createdAt: number;
};

// Free text typed on the canvas (T), in one of the Google Fonts from lib/fonts.ts
export type TextCard = BaseCard & { kind: "text"; text: string; font: string; size: number; color: string; bold?: boolean };
export type LinkCard = BaseCard & { kind: "link"; url: string; title: string; cite?: Citation };
export type ImageCard = BaseCard & {
  kind: "image";
  src: string;
  fallbackSrc?: string; // smaller copy to show if the original won't load
  caption?: string;
  sourceUrl?: string; // page or file it came from
  cite?: Citation;
  showCredit?: boolean; // show the credit line under the image (default true)
};
// A card generated by the research panel (artist, museum, article, exhibition, app, ...)
export type ResearchCard = BaseCard & {
  kind: "research";
  category: string; // research type id, see lib/researchTypes.ts
  name: string;
  subtitle?: string;
  image?: string;
  website?: string;
  sections: Section[];
  sources: Source[];
};

export type Card = TextCard | LinkCard | ImageCard | ResearchCard;
export type CardKind = Card["kind"];

export type CandidateStatus = "new" | "kept" | "skipped" | "added";

export type Candidate = {
  id: string;
  name: string;
  why: string; // one line: why this matches the prompt
  meta?: string; // short line like "author, publication, year" or "city, type"
  match?: "exact" | "related"; // exact = the thing you named; related = similar / matches your description
  sourceUrl?: string;
  sourceTitle?: string;
  status: CandidateStatus;
};

export type ResearchSession = {
  id: string;
  query: string;
  type: string; // research type id
  candidates: Candidate[];
  createdAt: number;
  mock?: boolean;
};

export type Frame = { w: number; h: number; preset: string };

export type Viewport = { x: number; y: number; zoom: number };

// A board has one or more pages; each page is its own canvas with the board's frame size.
export type Page = {
  id: string;
  name: string;
  cards: Card[];
  viewport?: Viewport;
};

// Folders on the home screen; a board sits in at most one
export type Folder = { id: string; name: string; createdAt: number };

export type Board = {
  id: string;
  name: string;
  folderId?: string; // undefined = not in a folder
  frame: Frame;
  pages: Page[];
  currentPageId?: string;
  viewport?: Viewport; // where you were looking on the canvas (all pages share one canvas)
  research: ResearchSession[]; // newest first, shared across pages
  createdAt: number;
  updatedAt: number;
};

// What the /api/card route returns
export type GeneratedCard = {
  name: string;
  subtitle?: string;
  website?: string;
  image?: string;
  sections: Section[];
  sources: Source[];
  mock?: boolean;
};
